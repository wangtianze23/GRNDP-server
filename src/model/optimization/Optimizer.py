from model.optimization.Constraint import RegulationConstraint,TargetConstraint
from model.optimization.Network import \
    Node, Path, Parameter, OptimizedRegulation
from model.optimization.NetworkRepresentation import PathRepresentation


class OptimizationResult:
    """
    The container class for the result of network optimization.
    """
    def __init__(self, regulations: list[OptimizedRegulation], 
                 targets: list[float], message = ''):
        """
        Initialize an OptimizationResult object.

        Parameters
        ----------
        regulations : list
            A list of OptimizedRegulation objects containing the optimized 
            regulations in a network.
        targets : list
            A list of float containing the optimized target values.
        message : str, optional
            A string representing the message generated by the optimizer.
            The default is an empty string.

        Returns
        -------
        None.
        """
        self.regulations = regulations
        self.targets = targets
        self.message = message

class NetworkOptimizer:
    """
    The class for optimizing transcription networks.
    """
    def __init__(self):
        """
        Initialize a NetworkOptimizer object.
        
        Returns
        -------
        None.
        """
        self.maxIteration = 100
        self.seed = None
        self.trajectoryCount = 1000
    
    def setMaximumIteration(self, maxIteration = 100):
        """
        Set the number of iteration for optimization.

        Parameters
        ----------
        maxIteration : int, optional
            An integer indicating the maximum number of iteration. 
            The default is 100.

        Returns
        -------
        None.
        """
        self.maxIteration = maxIteration
    
    def setSeed(self, seed = None):
        """
        Set the seed for the random number generator (RNG) when generating 
        sequences.

        Parameters
        ----------
        seed : int or NoneType
            An integer fed to the RNG, or None if no fixed seed is used.
            The default is None.

        Returns
        -------
        None.
        """
        self.seed = seed
    
    def setTrajectoryCount(self, trajectoryCount = 1000):
        """
        Set the number of trajectories for simulation of system dynamics.

        Parameters
        ----------
        count : int, optional
            An integer indicating the number of trajectories.
            The default is 1000.

        Returns
        -------
        None.
        """
        self.trajectoryCount = trajectoryCount
    
    def optimizeWithSpaceAndTarget(self, 
                                   nodeList: list[Node], 
                                   edgeList: list[RegulationConstraint], 
                                   targetList: list[TargetConstraint])\
                                  -> OptimizationResult:
        """
        Optimize a network with given topology and targets.

        Parameters
        ----------
        nodeList : list
            A list of Node objects indicating all entities in the network.
        edgeList : list
            A list of RegulationConstraint object indicating the regulations 
            among entities and the corresponding constraints on their 
            parameters during optimization.
        targetList : list
            A list of TargetConstraint objects indicating the target functions 
            to optimize.

        Returns
        -------
        OptimizationResult
            An OptimizationResult object containing the result of optimization.
        """
        optimizedRegulations = []
        for edge in edgeList:
            parameterSpace = edge.parameterSpace
            ### TODO: Implement the optimization procedure ###
            parameters = [Parameter(i, X.name, X.minValue) 
                          for i, X in enumerate(parameterSpace.parameterList)]
            optimizedRegulations.append(
                        OptimizedRegulation(ID = '', parameters = parameters))
        
        return OptimizationResult(optimizedRegulations, [0] * len(targetList))
    
    def visualize(self, nodeList: list[Node], 
                  optimizationResult: OptimizationResult, 
                  path: Path) -> PathRepresentation:
        """
        Visualize a specific path in a network after optimization.

        Parameters
        ----------
        nodeList : list
            A list of Node objects indicating all entities in the network.
        optimizationResult : OptimizationResult
            An OptimizationResult object containing the result of optimization.
        path : Path
            A Path object indicating the path to visualize.

        Returns
        -------
        PathRepresentation
            A PathRepresentation object containing the graphical 
            representation of the specified path.
        """
        return PathRepresentation(path.sourceIndex, path.targetIndex, None)
